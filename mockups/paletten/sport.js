function orb(p) {
  const R = 40, C = 48, vals = [0.86, 0.62, 0.74, null, 0.55, 0.7]
  const pts = vals.map((v, i) => { const a = Math.PI*2*i/6 - Math.PI/2; const r = 14 + (v ?? 0)*(R-14); return [C+Math.cos(a)*r, C+Math.sin(a)*r, v] })
  const d = pts.map(([x,y],i)=>(i?`L${x.toFixed(1)} ${y.toFixed(1)}`:`M${x.toFixed(1)} ${y.toFixed(1)}`)).join(' ')+' Z'
  const dots = pts.map(([x,y,v])=>`<circle cx="${x.toFixed(1)}" cy="${y.toFixed(1)}" r="2.6" fill="${v==null?'none':p.glow}" stroke="${p.glow}" stroke-width="1.3"/>`).join('')
  const grid=[1,.66,.33].map(f=>`<circle cx="${C}" cy="${C}" r="${(14+f*(R-14)).toFixed(1)}" fill="none" stroke="${p.line}"/>`).join('')
  return `<svg width="96" height="96" viewBox="0 0 96 96">${grid}<path d="${d}" fill="${p.accent}" fill-opacity=".22" stroke="${p.accent}" stroke-width="2"/>${dots}</svg>`
}
